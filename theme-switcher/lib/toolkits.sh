# Generators for the toolkits: GTK (2/3/4) and Qt (Breeze style + KDE color scheme).
# Sourced by theme-switch after a palette has been loaded.
#
# Qt apps read colors through the KDE platform theme (plasma-integration,
# QT_QPA_PLATFORMTHEME=kde), so a generated KDE color scheme themes every
# palette consistently, and open apps recolor live on a palette-change signal.

KDE_SCHEME="ThemeSwitch"

# "#rrggbb" -> "r,g,b" (KDE color format)
hex2rgb() {
	local h="${1#\#}"
	printf '%d,%d,%d' "0x${h:0:2}" "0x${h:2:2}" "0x${h:4:2}"
}

gen_gtk() {
	local dark=0 scheme="prefer-light" v
	[[ "$THEME_MODE" == "dark" ]] && { dark=1; scheme="prefer-dark"; }

	if [[ ! -d "/usr/share/themes/$GTK_THEME" && ! -d "$HOME/.local/share/themes/$GTK_THEME" ]]; then
		warn "GTK theme '$GTK_THEME' is not installed, GTK apps keep their current theme"
		return 0
	fi

	for v in 3.0 4.0; do
		write_file "$HOME/.config/gtk-$v/settings.ini" <<EOF
[Settings]
gtk-theme-name=$GTK_THEME
gtk-application-prefer-dark-theme=$dark
gtk-icon-theme-name=Adwaita
gtk-cursor-theme-name=Adwaita
gtk-cursor-theme-size=24
gtk-font-name=Adwaita Sans 11
EOF
	done

	write_file "$HOME/.gtkrc-2.0" <<EOF
gtk-theme-name="$GTK_THEME"
gtk-icon-theme-name="Adwaita"
gtk-cursor-theme-name="Adwaita"
gtk-cursor-theme-size=24
gtk-font-name="Adwaita Sans 11"
EOF

	# gsettings is what running GTK apps watch, so this switches them live.
	# Set the light/dark preference first: if the theme changed first, open
	# apps would load the new theme's variant for the old preference.
	gsettings set org.gnome.desktop.interface color-scheme "$scheme"
	gsettings set org.gnome.desktop.interface gtk-theme "$GTK_THEME"
}

kde_group() {
	local name="$1" bg="$2" bgalt="$3" fg="$4"
	cat <<EOF
[Colors:$name]
BackgroundAlternate=$(hex2rgb "$bgalt")
BackgroundNormal=$(hex2rgb "$bg")
DecorationFocus=$(hex2rgb "$ACCENT")
DecorationHover=$(hex2rgb "$ACCENT")
ForegroundActive=$(hex2rgb "$ACCENT")
ForegroundInactive=$(hex2rgb "$MUTED")
ForegroundLink=$(hex2rgb "$BLUE")
ForegroundNegative=$(hex2rgb "$RED")
ForegroundNeutral=$(hex2rgb "$YELLOW")
ForegroundNormal=$(hex2rgb "$fg")
ForegroundPositive=$(hex2rgb "$GREEN")
ForegroundVisited=$(hex2rgb "$PURPLE")

EOF
}

kde_colors() {
	echo "# Generated by theme-switch ($THEME_NAME) — do not edit, edit the palette instead."
	kde_group View "$BG0" "$BG1" "$FG1"
	kde_group Window "$BG1" "$BG2" "$FG1"
	kde_group Button "$BG2" "$BG3" "$FG1"
	kde_group Selection "$ACCENT" "$ACCENT" "$BG0"
	kde_group Tooltip "$BG1" "$BG2" "$FG1"
	kde_group Header "$BG1" "$BG2" "$FG1"
	kde_group "Header][Inactive" "$BG1" "$BG2" "$FG0"
	kde_group Complementary "$BG_DEEP" "$BG0" "$FG1"
	cat <<EOF
[ColorEffects:Disabled]
Color=$(hex2rgb "$BG1")
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=true
Enable=false

[General]
ColorScheme=$KDE_SCHEME
Name=$KDE_SCHEME

[KDE]
widgetStyle=Breeze

[Icons]
Theme=$KDE_ICONS

[WM]
activeBackground=$(hex2rgb "$BG1")
activeForeground=$(hex2rgb "$FG1")
inactiveBackground=$(hex2rgb "$BG1")
inactiveForeground=$(hex2rgb "$MUTED")
EOF
}

# KDE apps load the scheme named in [General] ColorScheme from
# ~/.local/share/color-schemes, so write it there as well as into kdeglobals.
gen_qt() {
	kde_colors | write_file "$HOME/.local/share/color-schemes/$KDE_SCHEME.colors"
	kde_colors | write_file "$HOME/.config/kdeglobals"
}

# Tell running KDE/Qt apps the palette changed (what plasma-apply-colorscheme does).
reload_qt() {
	dbus-send --session --type=signal /KGlobalSettings \
		org.kde.KGlobalSettings.notifyChange int32:0 int32:0 2>/dev/null || true
}
